# ---------------------------------------------------------------- helpers
def dtcg_color(hx):
    r, g, b = hex_to_rgb(hx)
    return {"colorSpace": "srgb", "components": [round(r / 255, 4), round(g / 255, 4), round(b / 255, 4)], "hex": hx}


def dim(v, unit="px"):
    return {"value": v, "unit": unit}


def tint(hx, pct):
    """Tint = colour at pct% opacity over white (how guidelines usually draw tints)."""
    a = pct / 100
    return rgb_to_hex([c * a + 255 * (1 - a) for c in hex_to_rgb(hx)])


def ext(item):
    e = {"status": item["status"]}
    if item.get("confidence"):
        e["confidence"] = item["confidence"]
    return {"zamakan": e}


def parse_shadow(css):
    m = re.fullmatch(r"\s*(-?[\d.]+)(?:px)?\s+(-?[\d.]+)(?:px)?\s+([\d.]+)(?:px)?(?:\s+(-?[\d.]+)(?:px)?)?\s+(.+)", css)
    if not m:
        return None
    x, y, blur, spread, col = m.groups()
    rgba = re.fullmatch(r"rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+))?\s*\)", col.strip())
    if rgba:
        r, g, b, a = rgba.groups()
        color = {"colorSpace": "srgb", "components": [round(int(c) / 255, 4) for c in (r, g, b)], "alpha": float(a or 1),
                 "hex": rgb_to_hex([int(r), int(g), int(b)])}
    elif col.strip().startswith("#"):
        color = dtcg_color(col.strip().upper())
    else:
        return None
    return {"color": color, "offsetX": dim(float(x)), "offsetY": dim(float(y)), "blur": dim(float(blur)),
            "spread": dim(float(spread or 0))}


def simple_dim(css):
    m = re.fullmatch(r"\s*(-?[\d.]+)(px|rem)?\s*", css)
    return dim(float(m.group(1)) if "." in m.group(1) else int(m.group(1)), m.group(2) or "px") if m else None


def src_str(item):
    out = []
    for s in item.get("sources", []):
        t = Path(s["file"]).name + (f" p{s['page']}" if s.get("page") else "")
        if s.get("method") and s["method"] != "text":
            t += f" ({s['method']})"
        out.append(t)
    return "; ".join(out)


# ---------------------------------------------------------------- tokens
def build_tokens(spec):
    colors = {c["id"]: c for c in spec["colors"]}
    t = {"$schema": "https://www.designtokens.org/schemas/2025.10/format.json",
         "$description": f"{spec['client']['name']}: generated by {TOOL} from spec.json. Do not edit; edit spec.json and rebuild."}
    t["color"] = {"$type": "color"}
    for c in spec["colors"]:
        meta = {k: c[k] for k in ("name", "name_ar", "group", "rgb", "cmyk", "pantone") if k in c}
        e = ext(c)
        e["zamakan"].update(meta)
        t["color"][c["id"]] = {"$value": dtcg_color(c["hex"]), "$description": c.get("usage", c["name"]), "$extensions": e}
    for tn in spec.get("tints", []):
        for pct in tn["steps_pct"]:
            if pct == 100:
                continue
            t["color"][f"{tn['color']}-{int(pct)}"] = {
                "$value": dtcg_color(tint(colors[tn["color"]]["hex"], pct)),
                "$description": f"{colors[tn['color']]['name']} {int(pct)}% tint (on white). {tn.get('usage', '')}".strip(),
                "$extensions": {"zamakan": {"status": "derived", "tint_of": tn["color"], "pct": pct}}}
    t["role"] = {"$type": "color"}
    for r in spec["color_roles"]:
        t["role"][r["role"]] = {"$value": "{color.%s}" % r["color"], "$description": r.get("usage", ""), "$extensions": ext(r)}
    t["font"] = {"$type": "fontFamily"}
    for f in spec["fonts"]:
        t["font"][f["id"]] = {"$value": [f["family"]] + f.get("fallback", []),
                              "$description": f"{f['script']} {f['role']}; weights {f['weights']}", "$extensions": ext(f)}
    t["type"] = {"$type": "typography"}
    for s in spec["type_scale"]:
        v = {"fontFamily": "{font.%s}" % s["font"], "fontSize": dim(s["size_px"]), "fontWeight": s["weight"],
             "lineHeight": round(s["line_height_px"] / s["size_px"], 3),
             "letterSpacing": dim(round(s.get("letter_spacing_em", 0) * s["size_px"], 2))}
        e = ext(s)
        if s.get("text_transform", "none") != "none":
            e["zamakan"]["textTransform"] = s["text_transform"]
        if s.get("color"):
            e["zamakan"]["color"] = "{color.%s}" % s["color"]
        t["type"].setdefault(s["script"], {})[s["level"]] = {"$value": v, "$extensions": e}
    if spec.get("spacing"):
        sp = spec["spacing"]
        t["space"] = {"$type": "dimension", "$description": f"base {sp['base_px']}px", "$extensions": ext(sp)}
        for i, v in enumerate(sp["scale_px"], 1):
            t["space"][str(i)] = {"$value": dim(v)}
    if spec.get("radii"):
        t["radius"] = {"$type": "dimension"}
        for r in spec["radii"]:
            d = simple_dim(r["value"])
            e = ext(r)
            if d is None:  # compound value (e.g. top corners only) → nearest single value + exact CSS in extension
                first = re.match(r"\s*(-?[\d.]+)(px)?", r["value"])
                d = dim(float(first.group(1)) if first else 0)
                e["zamakan"]["css"] = r["value"]
            t["radius"][r["id"]] = {"$value": d, "$description": r.get("usage", ""), "$extensions": e}
    if spec.get("shadows"):
        t["shadow"] = {"$type": "shadow"}
        for s in spec["shadows"]:
            v = parse_shadow(s["value"])
            e = ext(s)
            e["zamakan"]["css"] = s["value"]
            t["shadow"][s["id"]] = {"$value": v, "$description": s.get("usage", ""), "$extensions": e} if v else \
                {"$value": None, "$extensions": e}
    if spec.get("borders"):
        t["border"] = {}
        for b in spec["borders"]:
            e = ext(b)
            e["zamakan"]["css"] = b["value"]
            t["border"][b["id"]] = {"$type": "border", "$description": b.get("usage", ""),
                                    "$value": _border(b["value"]), "$extensions": e}
    return t


def _border(css):
    m = re.fullmatch(r"\s*([\d.]+)px\s+(solid|dashed|dotted|double)\s+(#[0-9A-Fa-f]{6})\s*", css)
    if not m:
        return None
    return {"color": dtcg_color(m.group(3).upper()), "width": dim(float(m.group(1))), "style": m.group(2)}


# ---------------------------------------------------------------- css
def css_font_faces(spec, font_assets):
    from fonts import read_font
    out = []
    for f in spec["fonts"]:
        for rel in font_assets.get(f["id"], []):
            info = read_font(OUT_ROOT / rel)
            if "variable_axes" in info and "wght" in info["variable_axes"]:
                lo, _, hi = info["variable_axes"]["wght"]
                weight = f"{int(lo)} {int(hi)}"
            else:
                weight = str(info["weight_class"] or 400)
            style = "italic" if info.get("italic") else "normal"
            fmt = {"ttf": "truetype", "otf": "opentype", "woff": "woff", "woff2": "woff2"}[Path(rel).suffix[1:].lower()]
            out.append(f"@font-face {{ font-family: '{f['family']}'; src: url('{rel}') format('{fmt}'); "
                       f"font-weight: {weight}; font-style: {style}; font-display: swap; }}")
    return out


def build_css(spec, font_assets):
    colors = {c["id"]: c for c in spec["colors"]}
    fonts = {f["id"]: f for f in spec["fonts"]}
    L = [f"/* {spec['client']['name']}: generated by {TOOL} from spec.json. Do not edit. */"]
    L += css_font_faces(spec, font_assets)
    L.append(":root {")
    for c in spec["colors"]:
        L.append(f"  --color-{c['id']}: {c['hex']};")
    for tn in spec.get("tints", []):
        for pct in tn["steps_pct"]:
            if pct != 100:
                L.append(f"  --color-{tn['color']}-{int(pct)}: {tint(colors[tn['color']]['hex'], pct)};")
    for r in spec["color_roles"]:
        L.append(f"  --role-{r['role']}: var(--color-{r['color']});")
    for f in spec["fonts"]:
        stack = ", ".join(f"'{x}'" if " " in x else x for x in [f["family"]] + f.get("fallback", []))
        L.append(f"  --font-{f['id']}: {stack};")
    for s in spec["type_scale"]:
        p = f"--type-{s['script']}-{s['level']}"
        L += [f"  {p}-family: var(--font-{s['font']});", f"  {p}-size: {s['size_px']}px;",
              f"  {p}-line: {s['line_height_px']}px;", f"  {p}-weight: {s['weight']};"]
        if s.get("letter_spacing_em"):
            L.append(f"  {p}-tracking: {s['letter_spacing_em']}em;")
    if spec.get("spacing"):
        for i, v in enumerate(spec["spacing"]["scale_px"], 1):
            L.append(f"  --space-{i}: {v}px;")
    for group, prefix in (("radii", "radius"), ("shadows", "shadow"), ("borders", "border")):
        for r in spec.get(group, []):
            L.append(f"  --{prefix}-{r['id']}: {r['value']};")
    L.append("}")
    L.append("/* Arabic: right-to-left, never letter-spaced */")
    L.append(".z-ar { direction: rtl; text-align: right; letter-spacing: 0 !important; }")
    for s in spec["type_scale"]:
        p = f"--type-{s['script']}-{s['level']}"
        decl = (f"font-family: var({p}-family); font-size: var({p}-size); line-height: var({p}-line); "
                f"font-weight: var({p}-weight);")
        if s.get("letter_spacing_em") and s["script"] != "arabic":
            decl += f" letter-spacing: var({p}-tracking);"
        if s.get("text_transform", "none") != "none":
            decl += f" text-transform: {s['text_transform']};"
        if s["script"] == "arabic":
            decl += " direction: rtl;"
        L.append(f".z-{s['script']}-{s['level']} {{ {decl} }}")
    _ = fonts
    return "\n".join(L) + "\n"


# ---------------------------------------------------------------- manifest
def build_manifest(spec, logo_assets, font_assets):
    colors = {c["id"]: c for c in spec["colors"]}
    bgref = lambda ids: [{"id": i, "hex": colors[i]["hex"]} for i in ids]  # noqa: E731
    logos, by_bg = [], {}
    for v in spec["logo"]["variants"]:
        logos.append({k: v[k] for k in ("id", "name", "kind", "orientation", "colorway", "usage", "min_size", "status")
                      if k in v} | {"files": logo_assets[v["id"]],
                                    "approved_backgrounds": bgref(v.get("approved_backgrounds", [])),
                                    "forbidden_backgrounds": bgref(v.get("forbidden_backgrounds", []))})
        for b in v.get("approved_backgrounds", []):
            by_bg.setdefault(b, []).append(v["id"])
    return {
        "client": spec["client"]["slug"], "generated_by": TOOL,
        "logos": logos,
        "logo_for_background": by_bg,
        "logo_rules": {k: spec["logo"][k]["text"] for k in ("clear_space", "on_photography") if k in spec["logo"]},
        "fonts": [{k: f[k] for k in ("id", "family", "role", "script", "weights", "fallback", "license") if k in f}
                  | {"files": font_assets.get(f["id"], [])} for f in spec["fonts"]],
        "formats": spec.get("layout", {}).get("formats", []) and [
            {k: v for k, v in f.items() if k not in ("sources", "confidence")} for f in spec["layout"]["formats"]],
        "graphic_elements": [{k: g[k] for k in ("id", "name", "description", "usage", "colors") if k in g}
                             for g in spec.get("graphic_elements", [])],
    }


# ---------------------------------------------------------------- contrast
def contrast_table(spec):
    colors = {c["id"]: c for c in spec["colors"]}
    roles = {r["role"]: r["color"] for r in spec["color_roles"]}
    bgs = sorted({roles[r] for r in roles if r.startswith(("background", "surface", "brand"))} |
                 {b for v in spec["logo"]["variants"] for b in v.get("approved_backgrounds", [])})
    rows = []
    for fg in spec["colors"]:
        for b in bgs:
            if fg["id"] == b:
                continue
            ratio = contrast_ratio(fg["hex"], colors[b]["hex"])
            rows.append({"fg": fg["id"], "bg": b, "ratio": round(ratio, 2), "grade": wcag_grade(ratio)})
    return rows


# ---------------------------------------------------------------- sources.md
def build_sources(spec, contrast):
    counts = {}
    for _, it in walk_items(spec):
        counts[it["status"]] = counts.get(it["status"], 0) + 1
    L = [f"# Sources: {spec['client']['name']}", "",
         f"Generated by {TOOL} from `spec.json`. **{sum(counts.values())} values**: "
         + ", ".join(f"{v} {k}" for k, v in sorted(counts.items())) + ".", "",
         "- **extracted**: stated in the client's files · **derived**: computed from extracted values · "
         "**proposed**: not in the client's files; suggested by the agent (needs sign-off)", ""]
    if spec.get("conflicts"):
        L += ["## ⚠ Conflicts", ""]
        for c in spec["conflicts"]:
            vals = "; ".join(f"`{v['value']}` ({src_str({'sources': [v['source']]})})" for v in c["values"])
            L.append(f"- **{c['topic']}**: {vals} → chose `{c['chosen']}`. {c['resolution']}"
                     + (" *Needs client confirmation.*" if c.get("needs_client_confirmation") else ""))
        L.append("")
    if spec.get("open_questions"):
        L += ["## Open questions for the client", ""] + [f"- {q}" for q in spec["open_questions"]] + [""]
    L += ["## Proposed values (not in client files)", "", "| item | value | rationale |", "|---|---|---|"]
    for path, it in walk_items(spec):
        if it["status"] == "proposed":
            L.append(f"| `{path}` | {_val(it)} | {it.get('rationale', '')} |")
    L += ["", "## Colours", "", "| id | name | HEX | group | status | source |", "|---|---|---|---|---|---|"]
    for c in spec["colors"]:
        L.append(f"| {c['id']} | {c['name']} {c.get('name_ar', '')} | `{c['hex']}` | {c['group']} | {c['status']} | {src_str(c)} |")
    L += ["", "## Contrast (WCAG 2.x, text on background)", "",
          "| text \\ bg | " + " | ".join(sorted({r['bg'] for r in contrast})) + " |",
          "|---|" + "---|" * len({r['bg'] for r in contrast})]
    bgs = sorted({r["bg"] for r in contrast})
    for fg in spec["colors"]:
        cells = []
        for b in bgs:
            r = next((r for r in contrast if r["fg"] == fg["id"] and r["bg"] == b), None)
            cells.append(f"{r['ratio']} {r['grade']}" if r else "—")
        L.append(f"| {fg['id']} | " + " | ".join(cells) + " |")
    L += ["", "AA needs 4.5 for body text, 3 for large text (≥24px, or ≥18.66px bold).", "",
          "## All values", "", "| item | value | status | conf. | source |", "|---|---|---|---|---|"]
    for path, it in walk_items(spec):
        L.append(f"| `{path}` | {_val(it)} | {it['status']} | {it.get('confidence', '')} | {src_str(it) or '—'} |")
    return "\n".join(L) + "\n"


def _val(it):
    for k in ("hex", "value", "text", "family", "name", "color", "role"):
        if k in it:
            v = str(it[k])
            if k == "family":
                v += f" {it.get('weights', '')}"
            return v.replace("|", "\\|")[:90]
    if "size_px" in it:
        return f"{it['size_px']}/{it['line_height_px']}px w{it['weight']} {it['font']}"
    if "scale_px" in it:
        return f"base {it['base_px']}: {it['scale_px']}"
    if "steps_pct" in it:
        return f"{it['color']} {it['steps_pct']}"
    if "style" in it:
        return f"{it['style']} {it.get('stroke_px', '')}px"
    return ""


# ---------------------------------------------------------------- DESIGN.md
def build_design_md(spec):
    import yaml
    colors = {c["id"]: c for c in spec["colors"]}
    roles = {r["role"]: r["color"] for r in spec["color_roles"]}
    fm = {"version": "alpha", "name": spec["client"]["name"],
          "description": f"Visual identity of {spec['client']['name']}. Generated by {TOOL}; source of truth is spec.json."}
    col = {c["id"]: c["hex"] for c in spec["colors"]}  # palette first; semantic names reference it
    mapping = [("primary", ["brand"]), ("secondary", ["brand-alt", "brand-secondary"]), ("tertiary", ["accent"]),
               ("neutral", ["text-primary"]), ("surface", ["background"]), ("on-surface", ["text-primary"]),
               ("background", ["background"]), ("on-background", ["text-primary"]), ("on-primary", ["text-inverse"])]
    for key, cands in mapping:
        r = next((roles[c] for c in cands if c in roles), None)
        if r and key not in col:
            col[key] = "{colors.%s}" % r
    fm["colors"] = col
    typo = {}
    names = {"display": "headline-display", "h1": "headline-lg", "h2": "headline-md", "h3": "headline-sm",
             "body": "body-md", "small": "body-sm", "label": "label-md"}
    fonts = {f["id"]: f for f in spec["fonts"]}
    for s in spec["type_scale"]:
        name = names.get(s["level"], s["level"])
        if s["script"] == "arabic":
            name = f"ar-{name}"
        d = {"fontFamily": fonts[s["font"]]["family"], "fontSize": f"{s['size_px']}px", "fontWeight": s["weight"],
             "lineHeight": round(s["line_height_px"] / s["size_px"], 3)}
        if s.get("letter_spacing_em"):
            d["letterSpacing"] = f"{s['letter_spacing_em']}em"
        typo[name] = d
    fm["typography"] = typo
    rounded = {}
    for r in spec.get("radii", []):
        d = simple_dim(r["value"])
        if d:
            rounded[r["id"]] = f"{d['value']}{d['unit']}"
    if rounded:
        fm["rounded"] = rounded
    if spec.get("spacing"):
        steps = ["xxs", "xs", "sm", "md", "lg", "xl", "2xl", "3xl", "4xl", "5xl"]
        fm["spacing"] = {steps[i] if i < len(steps) else f"s{i}": f"{v}px" for i, v in enumerate(spec["spacing"]["scale_px"])}
    comps = {}
    if "primary" in col and "on-primary" in col:
        comps["button-primary"] = {"backgroundColor": "{colors.primary}", "textColor": "{colors.on-primary}",
                                   "typography": "{typography.label-md}" if "label-md" in typo else None}
        if rounded:
            comps["button-primary"]["rounded"] = "{rounded.%s}" % ("sm" if "sm" in rounded else next(iter(rounded)))
        comps["button-primary"] = {k: v for k, v in comps["button-primary"].items() if v}
    if "surface" in col:
        comps["card"] = {"backgroundColor": "{colors.surface}", "textColor": "{colors.on-surface}"}
    if comps:
        fm["components"] = comps

    def rules(items):
        return [f"- {'Do' if it.get('kind') == 'do' else 'Don’t' if it.get('kind') == 'dont' else 'Note'}: {it['text']}"
                + (" *(proposed)*" if it["status"] == "proposed" else "") for it in items]

    B = [f"# {spec['client']['name']}" + (f" ({spec['client']['name_ar']})" if spec["client"].get("name_ar") else ""), "",
         "## Overview", "",
         f"{spec['client'].get('industry', '')}, {spec['client'].get('market', '')}. Visual personality: "
         f"{', '.join(spec['client'].get('visual_personality', []))}.",
         "This file is an export for DESIGN.md-aware tools. The full identity (logo rules, photography, Arabic typography) "
         "is in `brand.md` and `spec.json`.", "", "## Colors", ""]
    for c in spec["colors"]:
        B.append(f"- **{c['name']} ({c['hex']})**{' / ' + c['name_ar'] if c.get('name_ar') else ''}: {c.get('usage', c['group'])}")
    if spec.get("color_proportions_pct"):
        B.append("- Balance: " + ", ".join(f"{colors[k]['name']} {v}%" for k, v in spec["color_proportions_pct"].items()))
    B += ["", "## Typography", ""]
    for f in spec["fonts"]:
        B.append(f"- **{f['family']}** ({f['script']} {f['role']}, weights {', '.join(map(str, f['weights']))})")
    B.append("- Tokens prefixed `ar-` are the Arabic counterparts: set them right-to-left and never letter-space Arabic.")
    B += rules(spec.get("type_rules", []))
    B += ["", "## Layout", ""]
    lay = spec.get("layout", {})
    B += rules(lay.get("grids", []) + lay.get("rules", []))
    for f in lay.get("formats", []):
        B.append(f"- {f['name']}: {f['width_px']}×{f['height_px']}px, margin {f.get('margin_px', '?')}px"
                 + (f", safe zone {f['safe_zone_px']}" if f.get("safe_zone_px") else "")
                 + (f", logo {f['logo_placement']}" if f.get("logo_placement") else ""))
    if spec.get("spacing"):
        B.append(f"- Spacing base {spec['spacing']['base_px']}px" + (" *(proposed)*" if spec["spacing"]["status"] == "proposed" else ""))
    B += ["", "## Elevation & Depth", ""]
    B += [f"- `{s['id']}`: {s['value']}: {s.get('usage', '')}" + (" *(proposed)*" if s["status"] == "proposed" else "")
          for s in spec.get("shadows", [])] or ["- Flat: no elevation defined."]
    B += ["", "## Shapes", ""]
    B += [f"- `{r['id']}`: {r['value']}: {r.get('usage', '')}" + (" *(proposed)*" if r["status"] == "proposed" else "")
          for r in spec.get("radii", [])]
    for g in spec.get("graphic_elements", []):
        B.append(f"- **{g['name']}**: {g['description']} {g.get('usage', '')}")
    if comps:
        B += ["", "## Components", "", "Components are *derived* from colour roles and type tokens; the client guideline "
              "does not define UI components."]
    B += ["", "## Do's and Don'ts", ""]
    B += rules(spec.get("color_rules", []) + spec["logo"].get("misuse", []) + spec["logo"].get("rules", []))
    front = yaml.safe_dump(fm, sort_keys=False, allow_unicode=True, width=1000)
    return f"---\n{front}---\n\n" + "\n".join(B) + "\n"


# ---------------------------------------------------------------- preview
def build_preview(spec, manifest, contrast, css_name="tokens.css"):
    e = html.escape
