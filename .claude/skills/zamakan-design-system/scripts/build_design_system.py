OUT_ROOT = Path(".")


def copy_assets(spec, input_dir, out):
    logo_assets, font_assets = {}, {}
    for v in spec["logo"]["variants"]:
        logo_assets[v["id"]] = []
        for f in v["files"]:
            dst = Path("assets/logos") / Path(f).name
            (out / dst).parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(Path(input_dir) / f, out / dst)
            logo_assets[v["id"]].append(str(dst))
    for f in spec["fonts"]:
        for p in f.get("files", []):
            dst = Path("assets/fonts") / Path(p).name
            (out / dst).parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(Path(input_dir) / p, out / dst)
            font_assets.setdefault(f["id"], []).append(str(dst))
    return logo_assets, font_assets


def build(spec_path, input_dir, out, preview=True):
    global OUT_ROOT
    spec = load_json(spec_path)
    errors, warnings = validate(spec, input_dir)
    if errors:
        raise SystemExit("spec.json has errors; fix them first:\n  " + "\n  ".join(errors))
    out = Path(out)
    out.mkdir(parents=True, exist_ok=True)
    OUT_ROOT = out
    if Path(spec_path).resolve() != (out / "spec.json").resolve():
        shutil.copy2(spec_path, out / "spec.json")
    logo_assets, font_assets = copy_assets(spec, input_dir, out)
    tokens = build_tokens(spec)
    write_json(out / "tokens.json", tokens)
    (out / "tokens.css").write_text(build_css(spec, font_assets), encoding="utf-8")
    manifest = build_manifest(spec, logo_assets, font_assets)
    manifest["spec_sha1"] = hashlib.sha1(Path(spec_path).read_bytes()).hexdigest()[:12]
    write_json(out / "manifest.json", manifest)
    contrast = contrast_table(spec)
    (out / "sources.md").write_text(build_sources(spec, contrast), encoding="utf-8")
    (out / "DESIGN.md").write_text(build_design_md(spec), encoding="utf-8")
    (out / "preview.html").write_text(build_preview(spec, manifest, contrast), encoding="utf-8")
    result = {"out": str(out), "warnings": warnings, "files": sorted(p.name for p in out.iterdir())}
    if preview:
        try:
            render_png(out / "preview.html", out / "preview.png")
        except Exception as ex:  # noqa: BLE001 - preview is for humans; never block the build
            result["preview_error"] = str(ex)[:200]
    return result


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("spec")
    ap.add_argument("--input", required=True, help="client input folder (logo/font paths in spec are relative to it)")
    ap.add_argument("--out", required=True)
    ap.add_argument("--no-preview", action="store_true")
    a = ap.parse_args()
    r = build(a.spec, a.input, a.out, not a.no_preview)
    print(f"built {r['out']}: {', '.join(r['files'])}")
    for w in r["warnings"]:
        print("  warn", w)
    if r.get("preview_error"):
        print("  preview not rendered:", r["preview_error"])
    print(json.dumps({"ok": True}))


if __name__ == "__main__":
    main()
