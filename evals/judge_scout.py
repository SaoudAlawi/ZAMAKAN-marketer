#!/usr/bin/env python3
"""Blind side-by-side judgement of two scout runs (with and without the skill), for qualities checks can't see.

Usage:
  python evals/judge_scout.py packets --iteration 3 --root <workspace>
      for every scenario and run number with both configs graded: writes judge/<scenario>-run-K/packet.md (the brief, the
      rubric and the two deliverables as "A" and "B" in a random order, with tell-tale markers removed) and key.json (which
      is which; kept in judge-keys/, never given to the judge), plus a screenshot of each board/deck first screen as A.png / B.png
  python evals/judge_scout.py record <judge_dir> <answer.json>
      checks the judge's JSON answer against the rubric and stores it, mapped back to with/without, as judgement.json

The judge is a fresh agent that only sees packet.md and the two PNGs. bench_scout.py scorecard picks up judgement.json.
"""
import argparse
import json
import random
import re
import sys
import zipfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "evals"))
import grade_scout as GS  # noqa: E402

RUBRIC = {
    "insight": "Audience and market truths that are sourced, specific and non-obvious; reads like a strategist, not a summary.",
    "references": "Relevant to the brief, high quality (proven or crafted work), good range (local, category, far away), honest about what was checked.",
    "ideas": "Territories or lessons that are distinct, ownable by this client, grounded in the references and culturally sharp for Saudi Arabia/the Gulf.",
    "usefulness": "A creative team could kick off tomorrow: clear recommendation, risks, open questions and what to check first.",
    "presentation": "Easy to scan and pleasant to present (judge from the screenshot and the structure), on-brand where a brand was given.",
}
TELLS = re.compile(r"zamakan[-\w]*|reference[- ]scout|generated by [^\n.]*|built by [^\n.]*|references\.json|territories\.md|"
                   r"skill|R\d{2}\b", re.I)
MAX_CHARS = 32000
PRIORITY = [r"insight|what we (learned|know)|audience|truth", r"recommend", r"territor|direction|route|idea", r"compet|rival",
            r"pattern|lesson|learn|takeaway", r"white ?space|gap|opportunit", r"risk|watch|before|open question|next|caveat|gap"]


def sections_of(text):
    parts = re.split(r"\n(?=#{1,4} )", "\n" + text)
    return [p.strip() for p in parts if p.strip()]


def rank(sec):
    head = sec.split("\n", 1)[0].lower()
    return next((i for i, rx in enumerate(PRIORITY) if re.search(rx, head)), len(PRIORITY))


def readable(job):
    """What a person would read, strategy first: insights, recommendation, territories, competitors, patterns, then the
    references. Sections are taken from the richest deliverable (report > board > deck) and capped at MAX_CHARS."""
    texts = GS.deliverable_texts(job)
    docs = []
    for n, t in texts.items():
        if n.endswith((".json", ".jsonl", ".csv", ".txt", "brief.md", "README.md", ".pdf")):
            continue
        t = GS.as_outline(n, t) if n.endswith((".html", ".htm")) else t
        t = re.sub(r"data:[^\s\"')]{100,}", "", TELLS.sub("", t))
        t = re.sub(r"\n\s*\n+", "\n\n", t)
        kind = 0 if n.endswith(".md") else 1 if n.endswith((".html", ".htm")) else 2
        docs.append((kind, -len(t), n, t))
    if not docs:
        return "(no readable deliverable)"
    docs.sort(key=lambda d: (d[0] == 2, d[1]))  # the richest structured deliverable leads (a deck's text has no headings)
    main = docs[0]
    secs = sections_of(main[3])
    seen_heads = {s.split("\n", 1)[0].lower() for s in secs}
    for _, _, n, t in docs[1:]:  # strategy sections that only exist in another file (e.g. territories in a separate .md)
        for s in sections_of(t):
            if rank(s) < len(PRIORITY) and s.split("\n", 1)[0].lower() not in seen_heads:
                secs.append(s)
    secs.sort(key=rank)
    out, total = [], 0
    for s in secs:
        if total + len(s) > MAX_CHARS:
            out.append(s[:max(0, MAX_CHARS - total)] + "\n[…cut for length]")
            break
        out.append(s)
        total += len(s)
    return f"(main file: {Path(main[2]).name})\n\n" + "\n\n".join(out)


def screenshot(job, dst):
    from playwright.sync_api import sync_playwright
    sys.path.insert(0, str(REPO / ".claude/skills/zamakan-design-system/scripts"))
    from _common import launch_chromium
    board, deck = GS.largest(job, {".html", ".htm"}), GS.largest(job, {".pdf"})
    try:
        if board:
            with sync_playwright() as p:
                b = launch_chromium(p)
                pg = b.new_page(viewport={"width": 1280, "height": 1600})
                pg.goto(board.resolve().as_uri())
                pg.wait_for_timeout(800)
                pg.screenshot(path=str(dst))
                b.close()
            return True
        if deck:
            import pymupdf
            pymupdf.open(deck)[0].get_pixmap(dpi=80).save(str(dst))
            return True
    except Exception:  # noqa: BLE001
        return False
    return False


def packets(a):
    base = Path(a.root) / f"iteration-{a.iteration}"
    made = []
    for sc_dir in sorted(p for p in base.iterdir() if p.is_dir() and (GS.SCENARIOS / p.name / "scenario.json").exists()):
        sc = json.loads((GS.SCENARIOS / sc_dir.name / "scenario.json").read_text(encoding="utf-8"))
        brief = (GS.SCENARIOS / sc_dir.name / "brief.md").read_text(encoding="utf-8").split("\n> Test input")[0]
        for run in sorted((sc_dir / "with_skill").glob("run-*")):
            other = sc_dir / "without_skill" / run.name
            if not other.exists():
                continue
            out = base / "judge" / f"{sc_dir.name}-{run.name}"
            out.mkdir(parents=True, exist_ok=True)
            sides = [("with_skill", run), ("without_skill", other)]
            random.Random(f"{sc_dir.name}{run.name}{a.iteration}").shuffle(sides)
            key = {}
            body = []
            for label, (cfg, r) in zip("AB", sides):
                job = r / "outputs" / sc["job"]
                if not job.exists():
                    job = r / "outputs"
                key[label] = cfg
                shot = screenshot(job, out / f"{label}.png")
                body.append(f"## Deliverable {label}\n\n" + ("(screenshot: " + label + ".png)\n\n" if shot else "(no visual deliverable)\n\n")
                            + readable(job))
            keys = base / "judge-keys"  # outside the judge's folder: the judge never sees which side is which
            keys.mkdir(exist_ok=True)
            (keys / f"{out.name}.json").write_text(json.dumps(key) + "\n", encoding="utf-8")
            rubric = "\n".join(f"- **{k}** (1–5): {v}" for k, v in RUBRIC.items())
            (out / "packet.md").write_text(f"""# Blind judgement: {sc['title']}

You are a creative director at a Riyadh agency. Two teams answered the same request. Judge which answer a demanding
client team would rather receive. You don't know who made which; don't guess, and don't reward length, formatting
conventions or file names. Reward substance: truth, sharpness, usefulness, taste. Penalise invented or unsupported
claims, clichés the brief asked to avoid, and anything culturally off for Saudi Arabia.

## The request

{sc['request']}

{brief}

## Rubric

Score each deliverable on each criterion from 1 (poor) to 5 (excellent):
{rubric}

Reply with JSON only, in exactly this shape:
{{"A": {{"insight": n, "references": n, "ideas": n, "usefulness": n, "presentation": n}},
  "B": {{"insight": n, "references": n, "ideas": n, "usefulness": n, "presentation": n}},
  "winner": "A" | "B" | "tie", "reason": "two or three sentences: what decided it"}}

{chr(10).join(body)}
""", encoding="utf-8")
            made.append(str(out))
    print("\n".join(made))


def record(a):
    d = Path(a.judge_dir)
    key = json.loads((d.parent.parent / "judge-keys" / f"{d.name}.json").read_text(encoding="utf-8"))
    raw = Path(a.answer).read_text(encoding="utf-8")
    ans = json.loads(raw[raw.index("{"):raw.rindex("}") + 1])
    for side in "AB":
        assert set(ans[side]) >= set(RUBRIC), f"{side}: missing criteria"
        assert all(1 <= ans[side][k] <= 5 for k in RUBRIC), f"{side}: scores must be 1-5"
    assert ans["winner"] in ("A", "B", "tie")
    j = {"scores": {key[s]: ans[s] for s in "AB"}, "winner": key.get(ans["winner"], "tie"), "reason": ans.get("reason", ""), "key": key}
    (d / "judgement.json").write_text(json.dumps(j, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"{d.name}: winner {j['winner']} · " + " · ".join(f"{c} {sum(v.values())}/25" for c, v in j["scores"].items()))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("packets")
    p.add_argument("--iteration", type=int, required=True)
    p.add_argument("--root", required=True)
    p = sub.add_parser("record")
    p.add_argument("judge_dir")
    p.add_argument("answer")
    a = ap.parse_args()
    {"packets": packets, "record": record}[a.cmd](a)


if __name__ == "__main__":
    main()
